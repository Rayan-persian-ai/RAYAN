// Generates migrations/0003_seed_agents.sql from packages/shared/agents/*.json.
// Usage: npm run gen:agents-sql -w @rayan/api   (CI test agents.test.ts verifies the registry matches the manifests)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const agentsDir = join(here, "../../../packages/shared/agents");
const out = join(here, "../migrations/0003_seed_agents.sql");
const q = (s) => `'${String(s).replaceAll("'", "''")}'`;

const files = readdirSync(agentsDir).filter((f) => f.endsWith(".json")).sort();
const rows = files.map((f) => {
  const m = JSON.parse(readFileSync(join(agentsDir, f), "utf8"));
  return `  (${q(m.slug)}, ${q(m.name_fa)}, ${q(m.name_en)}, ${q(m.description)}, ${q(JSON.stringify(m.permissions))}, ${m.enabled ? 1 : 0}, ${q(m.version)}, unixepoch() * 1000, unixepoch() * 1000)`;
});
const sql = `-- GENERATED by scripts/gen-agents-sql.mjs from packages/shared/agents/*.json — do not edit by hand.
-- Seeds the agent registry (${rows.length} manifests). Later manifest changes are applied with POST /api/agents/sync.
INSERT INTO agents (slug, name_fa, name_en, description, permissions, enabled, version, created_at, updated_at) VALUES
${rows.join(",\n")}
ON CONFLICT(slug) DO NOTHING;
`;
writeFileSync(out, sql);
console.log(`wrote ${rows.length} agents to ${out}`);
